// 以及如实说它现在还在不在、不在时她能怎么办。
//
// 和别的 copy 模块一样：面向用户的每一句都在这儿，全中文、零术语（没有「路径」
// 「日志」「接口」这类词）。判断逻辑在 results.ts，界面在 ResultsPanel.tsx。

