// 「服务方自己忙不过来 / 这个月用完了」这组话（r16）。
//
// 事实现场（2026-09）：派活的模型网关欠费停机，真实原文是
// `503: {...insufficient credits to make this request...}`。王姐会遇到的是同一族：
// 公司的用量用完了、服务方在限流、服务方自己抽风几分钟。
//
// 这一组话和「断网」必须分开说，因为**出路不同**：
//   * 断网她能自己查（先用浏览器看看别的网页能不能打开）；
//   * 「服务方用不了」不是她能修的，她要做的是**等一会儿**，一直这样再告诉管网络的人。
// 她不该得到的答案是「你的文件有问题」，也不该是「你没配好账号」（那是 AUTH 的说法）。
//
// 三句话是一个完整的故事，放在一个模块里才不会各自漂移：
//   发生了什么 —— 「帮你干活的程序现在用不了，多半不是你做错什么。」
//   你能做什么 —— 「过几分钟再试一次。」
//   一直这样   —— 「把下面这段原文复制给管网络的同事。」
//
// 零术语：界面上不出现 429 / 503 / quota / 额度 这类词；技术原文照旧留在
// 「复制详情」里给技术同事看（#282 的分层）。copy-guard / readability / tone
// 三条闸门都扫得到这个文件。
import type { RecoveryCopy } from "./recovery.ts";

/**
 * 出错页上这条出路的两步（`recovery.ts` 的 SERVICE_BUSY 用）。
 *
 * 只有两步是有意的：先等（多半等一会儿就好），一直这样再找管网络的同事。
 * 不附「重新选一次文件」——那和服务方用不用得了毫无关系，只会让她以为是自己
 * 选错了文件。
 */
export const SERVICE_RECOVERY: {
  readonly wait: RecoveryCopy;
  readonly admin: RecoveryCopy;
} = {
  wait: {
    label: "过一会儿再试",
    why: "帮你干活的程序现在用不了，多半不是你做错什么。过几分钟再点这个按钮。",
  },
  admin: {
    label: "复制详情给管网络的同事",
    why: "一直这样，就把下面这段原文复制出来，发给管网络的同事，请他帮忙看看。",
  },
} as const;
