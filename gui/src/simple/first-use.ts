// r3 — 底部那三句例子，用过之后就该让位。
//
// 「该怎么说」是**第一次用的人**的门槛：三句人话摆在输入框下面，点一下就能照说。
// 但她做过至少一轮之后，这三句对她就从门槛变成了噪音——每次打字都要先绕过它们，
// 而小屏/显示缩放（125%/150%）下底部那一栏是不滚的，它多高就直接吃掉多少卡片。
//
// 所以：**没做过** → 照旧全展开（第一屏体验不变）；**做过至少一轮** → 默认收起，
// 只留一个 44px 的入口，她点一下还能展开（见 Home.tsx）。
//
// 判据只用一条**已有的真实事实**：store 里有没有完成过的轮次。那就是磁盘上的运行
// 记录（`store.runs()`，启动时由 `run_log` 恢复，见 store.ts 的 persistRun /
// refreshRuns），不新造状态机、不猜。拿不到这个事实就不该在这里做决定。

/**
 * 三句例子一开始展不展开。
 *
 * `finishedRuns` 就是 `store.runs()`：完成过的轮次（做了、做失败了、她中途停了，
 * 都会在结束时留下一笔）。空 → 她还没做过，展开；非空 → 默认收起。
 */
export function examplesStartOpen(finishedRuns: readonly unknown[]): boolean {
  return finishedRuns.length === 0;
}
