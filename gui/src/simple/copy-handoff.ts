// 「把这个结果文件发给别人」的面向用户中文。
//
// 结果侧原来只有「复制成微信能贴的文字」——那送的是**文字**，不是文件本身。可王姐
// 做完一张表之后，更常见的一步是**把这张表本身**交给同事或领导（对方打开还是表格，
// 还能接着改）。这一块补的就是那件事的引导：文件是哪个、在哪儿、怎么拖进微信。
//
// 红线（和 copy-share.ts 同一条，绝不放松）：微信**绝不自动发送**，产品里不存在
// 「调用微信发送」这条路径。这里只放话，告诉她**自己**怎么发，不做任何发送动作。
// 所以每一句都是「你来做」，没有一句是「我帮你发」。
//
// 和别的 copy 模块一样：全中文、零术语，不印机器路径（「路径」是黑名单词）。文件名
// 由界面用 run.ts 的 fileName() 取，位置用 location.ts 已有的定位句（复用，不新造）。

export const HANDOFF = {
  /** 这一小节的标题：一眼看出这是「发文件」，和上面「发文字」不是一回事。 */
  heading: "把这个文件发给别人",

  /** 和上面那段「复制成文字」分清：这里要发的是文件本身。 */
  intro: "上面那段是能贴进微信的文字；这里说的是把表格文件本身发出去，对方打开还是表格。",

  /** ① 文件是哪个（名字她本来就认得，所以只说名字，不念机器位置）。 */
  what: (name: string): string => `要发的文件：${name}`,

  /** ③ 怎么发：先让这个文件露出来。 */
  howOpen: "先点上面的「打开所在文件夹」，它就露出来了。",
  /** ③ 怎么发：用她最熟的那个动作——拖进微信窗口。 */
  howDrag: "用鼠标按住这个文件，拖进微信的聊天窗口里，松手就发过去了。",
  /** ③ 另一条熟路：微信自己的「发送文件」。 */
  howWechat: "也可以在微信里点「发送文件」，再到这个文件夹里把它选上。",

  /** 一直挂着的提醒：发不发由她决定，我们不替她发。 */
  notSent: "发不发、发给谁，都由你自己定。我不会替你发送，也不会替你点。",
} as const;
