// 「你说的这件事，大概是这几张卡」——她说了一句话、还没点任何卡时的那几句。
//
// 她的真实动作是**说一句话**（「我有两个表要比一下」），而不是先在 32 张卡里
// 找到该搜的那个词。所以提交一句话之后，先问她「你是想做这个吗」，把最像的
// 几张摆出来；点一张就走和点卡片**同一条路**（首页把选择交给 `onPickTask`）。
//
// 一句话都认不出来时不硬凑：如实说「我没看懂」，并指一条她自己走得通的路
// （从首页的卡片里挑一张）。她自己那句话也一条都不丢——「照我说的做」还是原来
// 那条自由路（`onSubmitText`），所以这个新增的提示只是多给几个入口，不挡她的路。
//
// 文案的规矩和别处一样：全中文、零术语。**不写「匹配」「算法」「相似度」**——
// 她会以为自己要懂一套规则；只写「你说的这件事，像是这几张卡」，这是产品在
// 帮她认，不是在给她看一份检索结果。
export const SUGGEST = {
  /** 她说了一句话之后，这一块的标题：一个问句，不是一串结果。 */
  title: "你是想做这个吗？",
  /** 一句说明：点一下会发生什么（走卡片那条路，不用再自己找）。 */
  hint: "点一张，我就照这件事往下做。",
  /**
   * 一个都认不出来时：如实说没看懂，并指出一条她自己走得通的路。
   *
   * 卡片列表就在这句话上面的滚动区里（输入框固定在底部），所以说的是「首页的
   * 卡片」，不写「下面」——写反了方向，她按图索骥会看错地方。
   */
  none: "我没看懂你想做哪件事。你可以从首页的卡片里挑一张。",
  /** 最像的几张都不是：还是照她原话走（原来那条自由路，一个字不改）。 */
  justDoIt: "都不是，照我说的做",
} as const;
