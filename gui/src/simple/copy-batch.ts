// 「把这批结果一次复制成微信能贴的文字」的面向用户中文。
//
// 她一次做了五份结果时，以前只能一份一份点开、一份一份复制。这里补的是那个出口的
// 话：点一下会发生什么（只是把她这批结果复制成**一段**文字，绝不替她发送）、开头
// 那句总起、以及有几份没能放进来时她能怎么办。
//
// 硬约束和 copy-share.ts 一样：全中文、零术语。特别是不印她本机的完整位置——
// 那段文字是发给同事的，机器位置对她没用，还可能泄露她电脑上的目录结构。
// 判断与拼段在 share.ts（纯逻辑、有单测），这里只放话。

export const BATCH = {
  /** 「我做的结果」面板上那个出口。 */
  copyButton: "一次复制成微信能贴的文字",
  /** 按钮旁边一直挂着的一句提醒：复制不等于发送。 */
  hint: "把这批结果复制成一段文字，你自己到微信里粘贴；Cante 不会替你发送。",
  /** 开头那句总起，按**真正放进去几份**生成（空表不算）。 */
  heading: (count: number): string => `这次一共 ${count} 份，都在下面。`,
  /** 每一份前面的小标题，带上它是第几份和它的名字（名字是她认得的文件名）。 */
  section: (index: number, name: string): string => {
    const label = name.trim() === "" ? "这份结果" : `「${name.trim()}」`;
    return `第 ${index} 份 ${label}`;
  },
  /** 复制成功。份数写清楚，她一眼知道这次交出去的是几份。 */
  copied: (count: number): string =>
    `已经把这 ${count} 份复制成一段文字了。打开微信，在要发的地方按 Ctrl+V 粘贴就行——发不发还是你自己决定。`,
  /** 复制本身没成功（例如系统不让写剪贴板）。 */
  copyFailed: "没能复制上。你可以打开其中一份，选中要发的内容自己复制。",
  /** 有几份放不进去：不是表格，或者这次读不出来。如实说清，不假装全都放进去了。 */
  skipped: (count: number): string =>
    `还有 ${count} 份没能放进去：它们不是表格，或者这次读不出来。你可以单独打开这几份处理。`,
  /** 这台电脑根本没有读表格的工具。 */
  toolUnavailable:
    "这台电脑还读不出表格里的内容，没法一起复制。你可以打开其中一份，选中要发的内容自己复制。",
  /** 这些结果里没有能复制的内容。 */
  empty: "这些结果里没有能复制的内容。",
  /** 工具在，但这次一份都读不出来（坏了、加密了、被占用了……）。 */
  readFailed:
    "这些结果暂时读不出来。你可以过一会儿再试，或者打开其中一份，选中要发的内容自己复制。",
} as const;
