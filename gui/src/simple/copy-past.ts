// 「上次也做成过」这一句（r10）。
//
// 她第二次做同一件事时，最怕的是**覆盖上次那份**（ROADMAP §1 画像：她放弃产品的
// 原因就是怕弄坏东西）。结果面板里那句「上次做出来的表放在哪儿，这里都记着」是
// 做**之后**才看得到的，她在点「开始」之前看不到——所以把这句话挪到确认页上，
// 让它在动手前先安她的心：上次那份做成了、还在，而且这次会另存为新文件。
//
// 两条硬规矩：
//   * 只说**文件名**，不出现完整的位置（copy-guard 会扫；微信里贴一整串位置对
//     她没用，还有泄露的风险）；
//   * 时间、文件名都从本机记录里来（`lastSuccessFor`），不猜、不编。
//
// 和别的 copy 模块一样：面向用户的每一句都在这儿，全中文、零术语。
export const PAST = {
  /** 上次那份做成了，叫什么名字、什么时候做的。 */
  line: (name: string, when: string): string => `上次也做成过：${name}（${when} 做的）。`,
  /** 她自己最担心那件事的正面回答：这次不会盖住上次那份。 */
  safe: "这次会另存为新文件，不会盖住它。",
} as const;
