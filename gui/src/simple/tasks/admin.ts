// 行政月度例事三张卡（#85）：按人合并多张表、找出两张表之间的变化、到期提醒。
//
// 这三件事骨架相同：多张表按人/编号对齐，然后挑出「变化」或「临期」的项。
// 对行政/财务来说它们每月都来一次，而且都有一个共同的风险——表靠猜来对齐。
// 所以三张卡的底线都写进指令：
//   * 靠猜才能对上的地方必须说出来（列成「需要你确认」），不许硬塞；
//   * 日期/写法不统一时先说明是怎么理解的，空值和坏值不许猜；
//   * 结果一律另存为新文件，原来的表只读。
//
// 写法和 excel.ts 一致：plan 是固定文字（确认页每次都一样），risks 是能被用户
// 对着自己文件核对的具体情况，prompt 走公共信封。
