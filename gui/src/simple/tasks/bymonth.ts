    "文件名里的日期写法很多（20240105、2024-01-05、1月5日），认不出来的会放进「时间看不清」文件夹，我不会猜一个月份给它，请你翻一眼再定它们归哪个月。",
    "新位置已经有同名文件时，我不会覆盖，会停下来问你是要加序号，还是这个文件先不动。",
