// 照片/截图里的表格（#48）。
//
// 这条曾经被判过「做不到」：协议只承载文本、本机没有 OCR。现在走的是云端视觉
// 助手——cante 的会话本身会声明它能不能看图（`ModelSpec.support_vision`），
// 能看的就逐格照抄，不能看的就在确认页如实说清。
//
// 这张卡的底线只有一条，但它是产品的立身之本：**宁可说不清，也不编一个数**。
// 看不清的格子一律留空并点出来；整张图看不清、或者这个设置根本看不了图，就先停
// 下来把话说清楚。手写体、盖章遮挡、拍照歪斜、一张图里挤了两张表、同一格两种
// 写法（1,200 与 1200）——每一种都在 risks 里写明怎么处理，好让用户对着自己的
// 照片核对。
//
// 写法沿用 invoice.ts 的样板：plan 是固定文字（确认页每次都一样），risks 是能被
// 用户对着自己照片核对的具体情况，prompt 走公共信封。
import type { TaskDef } from "./types.ts";
import { buildPrompt } from "./prompt.ts";

/** 会被当成图片的扩展名（照片和截图）。 */
const IMAGE_TYPES = ["jpg", "jpeg", "png", "heic", "heif", "webp", "bmp", "tif", "tiff"];

/** #48 —— 照片或截图里的表格，抄成一张 .xlsx。 */
const table: TaskDef = {
  id: "vision.table",
  title: "把照片或截图里的表格变成 Excel",
  example: "把这张表的照片变成 Excel，看不清的地方空着，别猜",
  group: "表格",
  needs: "files",
  accept: IMAGE_TYPES,
  plan: [
    "先看一眼你给的图片，说清楚能看清哪些行、哪些列、哪些数字",
    "一格一格照抄：表头、每一行、每一列都按图片里的位置来",
    "看不清的格子一律留空，并指出是第几行第几列的哪一格、为什么看不清",
    "结果另存为一个新的 Excel 文件，原来的图片一张都不动",
  ],
  risks: [
    "手写体的数字容易认错（1 像 7、0 像 6、6 像 8）；遇到这种我会把那一格留空并指给你，绝不替你猜一个数字填上。",
    "公章、污渍、折痕、手指挡住格子的时候，被挡住的内容我不会填，会在结果里点出是第几行第几列被挡住了。",
    "拍照拍歪、光线反光、边缘没拍全的时候，某几列可能对不上位；我会说明哪几列没对准，请你对着照片核对。",
    "一张照片里挤了两张表、或者好几张照片要拼成一张表的时候，我会先停下来说明，按你确认的摆放方式来，不会自己拼。",
    "同一个格子有两种写法（比如 1,200 和 1200，或者 2024.1.5 和 2024年1月5日）时，我会照看到的原样写下来并标出来，不会替你统一成一种。",
  ],
  prompt(files, instruction) {
    return buildPrompt({
      what: "把下面这些图片里的表格抄成一张 Excel 表，一格一格照抄。图片可能是拍的照片，也可能是截图。",
      files,
      how: [
        "逐张打开图片，先用一两句话告诉我你看到了什么：大概几行、几列、表头是什么、有没有合并单元格。如果给的是一个装满图片的文件夹，就把文件夹里的图片逐张看一遍。",
        "一格一格照抄：表头、每一行、每一列都按图片里的位置来。数字和文字都照原样，不要改写法、不要四舍五入、不要替用户统一格式。",
        "看不清就留空，不许猜：任何一个看不清的格子都一律留空，并在结果里点出来——是第几行、第几列的哪一格、为什么看不清。绝对不要自己编一个数字或文字填上。",
        "如果整张图都看不清（太模糊、反光、拍歪了、只拍到一半），或者你根本看不了图片，就先停下来告诉我这件事现在做不了，不要硬编一张表出来。宁可说清做不到，也不要给一张可能错的表。",
        "遇到这些情况按上面的规矩处理，不要自作主张：手写体的数字、公章或污渍挡住格子、拍照歪斜导致列对不上、一张图里有多张表、好几张照片要拼成一张表、同一个格子有两种写法（1,200 和 1200）。拿不准的就留空并指出来，要拼要摆的等我确认。",
        "结果另存为一个新的 Excel 文件（.xlsx），放在第一张图片旁边，文件名以「结果_图片表格」开头。如果这台电脑有 cante-sheets，就用它把结果写成 .xlsx。原图只读：原来的图片一张都不要改、不要删、不要移动。",
        "结果里的每一行后面加一列「来自哪张图」，写清楚这一行是从哪一张图片抄来的，方便用户对着照片核对。",
      ],
      instruction,
      done: "一共看了几张图片、抄了几行几列、哪些格子看不清以及分别是第几行第几列、有没有整张图看不清或这个设置看不了图、结果文件的完整位置。",
    });
  },
  summaryHints: [
    "一共看了几张图片",
    "哪些格子看不清、在第几行第几列",
    "有没有整张图看不清",
    "结果文件在哪个位置",
  ],
};

export const VISION_TASKS: TaskDef[] = [table];
