// 个人工作总结 / 述职（#192 B）。
//
// 调研里「怎么写日常琐事才不显得碎」是**真实搜索**（见 gui/ROADMAP.md §6.5）：王姐
// 每个季度都要把一堆零碎的日常，写成一份看起来有条理、能交上去的总结。文书族已有
// 通知 / 请假条 / 工作汇报，但没有这一张「把流水账归并成总结」的变体。
//
// 这张卡最容易出的两个错，也正是这条搜索背后她最怕的两件事：
//   * **编数字**——流水账里没写的成绩，被写成一个像真的数字，交上去她担责；
//   * **更碎**——把几十条琐事原样罗列，读起来比不写还乱，总结该做的是归并。
// 所以三条规矩写死在指令里：没写的数字一律不许补；琐事要归并成几条；哪几件算重点
// 她没说时先停下来问，不要自己定了就当数。
//
// 来料是她的流水账，最顺手的一步是「选中、复制、贴进来」（和 wechat.rollcall 同一
// 条路），所以这张卡是 needs: "text"：不用先存成文件，直接把那段字贴进来就能做。
// 指令里也写明「内容可能来自文件、也可能整段贴进来」——这是微信粘贴入口那两张卡的
// 现成写法，来料不管是哪一种都按同一套做法处理。
//
// 写法沿用 document.ts 的样板：plan 是固定文字（确认页每次都一样），risks 是能对着
// 自己流水账核对的具体情况，prompt 走公共信封（./prompt.ts）。
import type { TaskDef } from "./types.ts";
import { buildPrompt } from "./prompt.ts";

const worksummary: TaskDef = {
  id: "doc.worksummary",
  title: "把这段时间做的事写成一份总结",
  example: "把我这三个月的流水账写成一份工作总结，别写得太长",
  group: "文书",
  needs: "text",
  plan: [
    "先把你贴进来的流水账从头看一遍，理出到底做了哪几件事",
    "同一件事分几次记的归并到一起，不逐条罗列",
    "按「做了什么、结果怎样、下面打算」排成一份总结",
    "内容另存为一个新文件，原来的东西一动不动",
  ],
  risks: [
    "我只会写你流水账里提过的事：你没写的数字、金额、比例、名次、人数，我一个都不会补，需要的地方会用「（请补充）」留空，请你补一句。",
    "哪几件算重点是我按常见写法挑的，可能和你想的不一样；我会把挑成重点的那几条单独列出来，请你核对、告诉我该换哪一条。",
    "一件事分几次记、说法又不一样时，我可能把本来两件事并成一条；我会在每条后面标出它来自你流水账里的哪几条，请你对着看。",
    "总结的口吻和详略我按常见的写法定，不一定符合你们单位的要求；拿到后请你核对一下，告诉我你们的习惯，我再调。",
  ],
  prompt(files, instruction) {
    return buildPrompt({
      what: "把用户给的流水账、工作记录，归并成一份有条理的个人工作总结，另存为一个新文件。",
      files,
      how: [
        "先看用户给的内容，用一两句话告诉我：你从中理出了几件事、有没有看不清或者太笼统的地方。要写的流水账可能来自用户选的文件，也可能整段贴在【用户的原话】里；两种都按下面的做法处理，不要因为没选文件就不做。",
        "按「做了什么、做出的结果或影响、下面打算」三块来写。同一件事分几次记下的、说法不一样的，归并成一条，不要逐条罗列。",
        "归并以后，整篇总结落在几条主要事情上，按分量轻重排：先说重要的。几条按内容多少定，但不要为了显得多，把一件小事拆成好几条。",
        "每一条后面用括号标出它来自你流水账里的哪几条（写成「（来自：原话第 X 条）」），这样用户一眼就能看出你有没有把两件事并到一起、有没有漏。",
        "数字和成绩只能照用户给的内容写：用户没写到的数字、金额、比例、名次、人数，一律不要补、不要估、也不要用常见的数字顶上；需要数字的地方用「（请补充）」留空，写完提醒用户填。",
        "哪几件算重点，用户如果没说清楚，先把你的判断告诉用户、说明你挑了哪几条、为什么，拿不准就先停下来问一句，不要自己定了就当数。",
        "写成一份能直接交上去的东西：分块清楚，用大白话。不要全是「认真完成」「积极配合」这类空话，每条尽量说清做了什么、有什么结果。",
        "流水账里读不懂、看不出是什么事的条目，不要丢掉，也不要自己猜一个，单独列在最后并写清是原话里的哪几条。",
        "结果另存为一个新文件：选了文件就放在那个文件旁边（同一个文件夹），一个文件都没选、内容全是贴进来的，就放在桌面。优先存成 Word 文档，存不了就存成纯文本。文件名用中文，一眼能看出是什么，例如「结果_工作总结」；已经有同名文件就在后面加序号，绝对不要覆盖已有文件。读过的原文件不要改、不要删、不要覆盖。",
      ],
      instruction,
      done: "一共归并成几条、哪几条你当成了重点、有哪些地方留了「请补充」需要用户填、有没有你没看懂的原话、结果文件放在哪里。",
    });
  },
  summaryHints: ["一共归并成几条", "哪几条被当成重点", "哪些地方需要你补充", "结果文件在哪个位置"],
};

export const WORK_SUMMARY_TASKS: TaskDef[] = [worksummary];
