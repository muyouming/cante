// 查资料（#54）：上网查一件事，整理成一页带来源的说明。
//
// 行政/财务经常要查政策、标准、办事流程（「差旅费标准」「社保基数调整」
// 「年检要交什么材料」），然后整理成一页交上去。这张卡和别的卡有一个根本区别：
// 答案不在用户的文件里，而在网上——所以它最容易出的错不是「算错」，而是
// 「编一个像真的数字」。三条底线必须写死在指令里，不能指望助手临场记得：
//
//   * 每一条结论后面都要写出来源（网页标题 + 网址，或发布单位的名称）；
//     查不到就说查不到，绝对不要编来源、也不要编数字；
//   * 文件最上面写清楚是什么时候查的——政策、标准、办事流程时效性极强，
//     同名文件又多，年份和地区差一点结论就完全不同；
//   * 不能上网、或者没有能上网查的工具，就直接说查不了，凭记忆答是我们
//     最怕的失败形态。
//
// 写法沿用 excel.ts 的样板：plan 是固定文字（确认页每次都一样），risks 是
// 能对着结果核对的实际情况，prompt 走公共信封。
