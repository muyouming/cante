// 发票族（#83）：电子发票 PDF 汇总成台账、按发票号码查重、台账与报销明细核对。
//
// 为什么是这三张卡片：财务每个月都要把一堆电子发票 PDF 手抄进 Excel，这是最高频、
// 也最容易抄错的一段活。三张卡正好对应三个动作——读数、找重、对账，每一步都只
// 产出新文件，原来的发票和表格一份都不碰。
//
// 写法沿用 excel.ts 的样板：plan 是固定文字（确认页每次都一样），risks 是能被用户
// 对着自己文件核对的具体情况，prompt 走公共信封。发票字段一律照原文搬，拿不到的
// 留空，绝不用别的发票补；扫描件/乱码先停下来说明，不把噪声当结果。
import type { TaskDef } from "./types.ts";
import { buildPrompt } from "./prompt.ts";

const SHEET_TYPES = ["xlsx", "xls", "csv"];

/** #83（一）—— 一批电子发票 PDF 变成一张台账。 */
const ledger: TaskDef = {
  id: "invoice.ledger",
  title: "发票 PDF 汇总成台账",
  example: "把这堆电子发票整理成一张台账，写上发票号码、开票日期、销方名称和价税合计",
  group: "表格",
  needs: "files",
  accept: ["pdf"],
  plan: [
    "先逐份打开发票 PDF，看看每份里能读到哪些信息",
    "把发票号码、开票日期、销方名称、价税合计一笔一笔读出来，一张发票一行",
    "读不到的字段留空，并把哪几份读不了、为什么读不了一并记下来",
    "台账另存为一个新的表格文件，原来的 PDF 一份都不动",
  ],
  risks: [
    "发票版式千差万别，同一个字段的叫法不统一（「价税合计」也可能印成「合计金额」「小写」），对不上意思的字段我会留空，不会照别的发票补一个。",
    "一份 PDF 里印了不止一张发票（一页两张、或前后连着开）时，我可能只抽到第一张，其余会漏；我会拿发票号码的个数提醒你可能不止一张。",
    "扫描或拍照的发票没有文字层，读出来是空的或是乱码（工具会明确告警，并停下退出）。遇到这种我会先告诉你是哪几份，请你核对原件，不会把乱码当成结果。",
    "我只照原文搬「价税合计」这一栏，不做税额、价税分离这类税务上的判断，也不会替你改一个数。",
  ],
  prompt(files, instruction) {
    return buildPrompt({
      what: "把下面这一批电子发票 PDF 里的信息抽出来，整理成一张台账，一张发票一行。",
      files,
      how: [
        "先把这一批 PDF 逐份读一遍，从文字里找出发票号码、开票日期、销方名称、价税合计这四样。读不出来的字段就留空，不要猜、不要照别的发票编一个。",
        "版式不一样没关系：字段的叫法可能不同（比如「价税合计」也可能写成「合计金额」「小写金额」），意思能对上就抽；实在对不上就先跳过这个字段、留空，并在最后告诉我。",
        "表头固定成这四列，顺序不要变：发票号码、开票日期、销方名称、价税合计。在这四列后面再加一列「来自哪个文件」，写清楚这一行出自哪份 PDF。",
        "金额只照原文搬「价税合计」那一栏，不要做税额、价税分离这类税务上的判断。日期和发票号码按原样保留，号码前面的 0 不要丢。",
        "如果一份 PDF 里印了不止一张发票（一页两张、或前后连在一起），先告诉我，并按你能认出的每一张各写一行；只抽到第一张时要说清楚。",
        "如果工具提示这份 PDF 没有文字层、或者抽出来的文字是乱码，先停下来告诉我（这类多半是扫描件或拍照的），不要把它当成一份正常发票，也不要用空白占一行。",
        "如果这台电脑没有能读 PDF 或能写表格的工具，先停下来告诉我，不要硬做。",
        "结果另存为一个新文件（.xlsx），放在第一份 PDF 旁边，文件名以「结果_发票台账」开头。原来的 PDF 一份都不要改、不要删、不要移动。",
      ],
      instruction,
      done: "一共读了几份发票、成功整理了几行、哪几份读不了以及为什么、有没有字段缺失（哪张发票缺哪个字段）、结果文件的完整位置。",
    });
  },
  summaryHints: ["一共读了几份发票", "哪几份读不了、为什么", "有没有哪些字段是空的", "结果文件在哪个位置"],
};

/** #83（二）—— 按发票号码找重复，只标不删。 */
const dupes: TaskDef = {
  id: "invoice.dupes",
  title: "找出重复的发票（只标不删）",
  example: "帮我看看这些发票里有没有重复的，把重复的标出来，别删",
  group: "表格",
  needs: "files",
  accept: SHEET_TYPES,
  plan: [
    "先打开表格，确认哪一列是发票号码（列名可能不叫这个，先问你）",
    "按发票号码找出同一个号码出现两次以上的行",
    "每一组重复列出：是哪几行、分别来自哪个文件、金额是否一致",
    "结果另存为一个新文件，只标出来，原来的一行都不删",
  ],
  risks: [
    "号码那一列可能不叫「发票号码」（也可能叫「发票号」「票据号码」）。哪一列是号码列我会先跟你确认，没确认就不动手。",
    "号码里的空格、全角半角、短横线差异（「0123 4567」和「01234567」）我会当成同一张来比，但会在结果里单独列出来，方便你核对。",
    "号码那一列是空的、或者一格里写了两个号码的，我会单独列成「号码看不清」，不拿它去和别人比。",
    "只标出来，不删行、不改原来的表；删不删、删哪一条由你决定。",
  ],
  prompt(files, instruction) {
    return buildPrompt({
      what: "在下面这几张表格里，按发票号码找出重复的发票，只标出来，不删任何一行。",
      files,
      how: [
        "先把用户给的表格逐张读一遍，告诉我每一张的列名，并指出哪一列最像发票号码。如果这一列不叫「发票号码」，先问一句确认，再动手。",
        "按发票号码找重复：同一个号码出现两次或两次以上，就算重复。号码里的空格、全角半角、短横线差异先统一了再比，但要在结果里写明你统一过哪些写法。",
        "每一个重复的号码，列出：这个号码出现在哪几行、分别来自哪张表或哪个文件、这几行的金额分别是多少、金额是否一致。",
        "金额不一致时，把每一行的金额原样列出来，不要自己算一个合计，也不要取一个平均值。",
        "号码那一列是空的、或者一格里写了两个号码的，单独列成「号码看不清」，不要拿它去和别人比。",
        "结果另存为一个新文件，放在第一张表旁边，文件名以「结果_发票查重」开头。只标出来，不要删行、不要改原来的表。",
      ],
      instruction,
      done: "一共看了多少行、找到几组重复、每组重复的号码和来自哪几行、金额有没有对不上的、有多少行号码看不清、结果文件的完整位置。",
    });
  },
  summaryHints: ["一共看了多少行", "找到几组重复", "有没有金额对不上的", "结果文件在哪个位置"],
};

/** #83（三）—— 发票台账和报销明细对一遍，固定分三桶。 */
const crosscheck: TaskDef = {
  id: "invoice.crosscheck",
  title: "发票台账和报销明细对一遍",
  example: "把这张发票台账和这份报销明细对一下，看看哪些对不上",
  group: "表格",
  needs: "files",
  accept: SHEET_TYPES,
  plan: [
    "两张表各读一遍，先跟你确认靠哪一列对上",
    "按确认的方式分成三桶：只在台账里、只在明细里、两张都有但金额不一样",
    "每一桶写清楚来自哪一行、两边的原文分别是什么",
    "结果另存为一个新文件，两张原表都不动",
  ],
  risks: [
    "两张表靠什么列对上，我会先问你确认（发票号码，还是金额加日期），没确认就不动手配对。",
    "对不上的原因可能是两张表列名不同（「价税合计」和「报销金额」）或写法不同，我只会写「对不上」，不会直接判定成你漏报销了，请你对着两张原表核对。",
    "同一个号码在明细里出现两次（分次报销）时，我会把两条都列出来，不会自己合并成一条。",
    "两边金额的单位或小数位不一样时（元 和 万元、两位小数和一位），数字可能对不上；我会把两边读到的原值都列出来，让你核对。",
  ],
  prompt(files, instruction) {
    return buildPrompt({
      what: "把下面这张发票台账和这张报销明细对一遍，找出对不上的地方。",
      files,
      how: [
        "先把两张表各读一遍，告诉我它们各有哪些列，并指出最可能用来配对的那一列。",
        "在动手配对之前，先问用户确认靠哪一列对上：是发票号码，还是金额加日期。用户确认了再继续；没确认就先停在这里。",
        "按确认的方式配对，分成三桶：只在台账里的、只在明细里的、两张都有但金额不一样的。",
        "每一桶都要写清楚来源行号：这一条在台账里是第几行、在明细里是第几行，并把两边的原文照抄出来。",
        "列名不同但意思相同的（比如「价税合计」和「报销金额」），先告诉用户你打算按它们配对，不要自己认定。",
        "对不上的先只写「对不上」，不要下「漏报销」「重复报销」这种结论；原因可能是列名或写法不同，留给用户核对。",
        "结果另存为一个新文件，放在第一张表旁边，文件名以「结果_发票核对」开头，三桶分成三块。两张原表都不要改、不要删、不要覆盖。",
      ],
      instruction,
      done: "你按哪一列配的对、三桶里各有多少条、只在台账里的是哪几行、只在明细里的是哪几行、金额对不上的是哪几行、结果文件的完整位置。",
    });
  },
  summaryHints: ["按哪一列配的对", "只在台账里的有几行", "只在明细里的有几行", "结果文件在哪个位置"],
};

export const INVOICE_TASKS: TaskDef[] = [ledger, dupes, crosscheck];
