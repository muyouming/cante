/** #49 (third) — find copies, delete nothing. */
const dupes: TaskDef = {
  id: "files.dupes",
  title: "找出重复的文件，列一份清单",
  example: "帮我找出这个文件夹里内容一样的文件，列个清单",
  group: "文件",
  needs: "folder",
  plan: [
    "扫描文件夹里的文件，先按大小分组，省掉大部分比较",
    "大小一样的再比内容，内容完全一致才算重复",
    "每一组重复保留哪一份给个建议，其余列进清单",
    "清单另存为新文件，不删任何文件",
  ],
  prompt(files, instruction) {
    return buildPrompt({
      what: "找出文件夹里内容完全一样的文件，列成一份清单。这个任务只找、只列，不要删除或移动任何文件。",
      folder: files[0] ?? "",
      how: [
        "先把整个文件夹里的所有文件扫一遍（包含子文件夹），把每个文件的大小和完整位置记下来。",
        "先按大小分组，大小不一样的肯定不是重复，省掉比较。大小一样的，再一份一份比对内容，内容完全一致才算重复。",
        "图片和视频这类文件，如果内容一样但被重新存过一次（大小略有差别），也单独列出来提醒我，但不要和「完全一样」混在一起。",
        "每一组重复文件：列出这一组有几个、每个的完整位置、每个多大、内容完全一样到哪一步。",
        "每一组给出建议：留哪一份（建议留最早创建或者位置最清楚的那一份），其余的建议删掉。但只写建议，不要真的删。",
        "把清单存成一个新文件，放在这个文件夹里，文件名以「结果_重复文件清单」开头。",
      ],
      instruction,
      done: "找到几组重复文件、一共多出来多少个、大概能省下多少空间、你对每一组建议留哪一份、清单文件的完整位置。",
    });
  },
  summaryHints: ["找到几组重复文件", "一共多出来多少个", "大概能省下多少空间", "清单文件在哪个位置"],
};

