// Excel and spreadsheet jobs (#45, #46, #47).
//
// These are the cards a finance or admin user reaches for every month, so the
// plans are written to be boringly predictable and the prompts avoid anything
// that would make the assistant improvise with someone's numbers.
import type { TaskDef } from "./index.ts";
import { buildPrompt } from "./index.ts";

const SHEET_TYPES = ["xlsx", "xls", "csv"];

/** #45 — the flagship: many sheets in, one clean sheet out. */
const merge: TaskDef = {
  id: "excel.merge",
  title: "把几张表合成一张（自动去掉重复行）",
  example: "把这三个月的销售表合成一张，重复的记录只留一条",
  group: "表格",
  needs: "files",
  accept: SHEET_TYPES,
  plan: [
    "先逐张打开，确认每张表的列名能不能对上",
    "以第一张表的列名为准，把所有表的行上下拼在一起",
    "每一格都完全一样的重复行，只留第一条，并数出去掉了几条",
    "结果另存为一个新文件，原来的表一张都不动",
  ],
  risks: [
    "两张表的列名只差一点点（比如「金额」和「金额（元）」）时，我会按意思对齐到同一列，并在结果里单独说明是哪两列，请你核对别对错。",
    "表里有合并单元格时，列名可能读不全，合并后的表头会缺字。",
    "看着一样、其实有一格不同（多一个空格、全角半角不同）的行，我会当成两条都留下，不会替你删掉。",
    "日期和编号（比如 2024-01-05、编号 001）在 Excel 里存过之后写法可能已经变了，我只能按现在读到的写。",
  ],
  prompt(files, instruction) {
    return buildPrompt({
      what: "把下面这几张表格合并成一张，并且去掉完全重复的行。",
      files,
      how: [
        "按顺序逐张打开表格，把每一张的第一行当作列名。如果哪张表的第一行不是列名，先告诉我。",
        "以第一张表的列名为准：名字一样的列直接对齐；名字不一样但意思明显相同的（比如「金额」和「金额（元）」），按意思对齐到同一列，并在结果里单独列出「哪两列被当成同一列」，让用户核对；只有实在拿不准是不是同一列的，才停下来问用户。某一列哪张表没有，就留空；多出来的列放到最后，原样保留。",
        "把所有表的行按顺序上下拼起来。每一格的原始内容和格式都要保住：日期还是日期，数字还是数字，编号前面的 0 不要丢掉。",
        "去掉重复行：每一格内容都完全相同的行只保留第一条，顺序按原来的先后。只要有任意一格不一样，就都保留。",
        "在最后一列加上「来自哪张表」，写清楚这一行原本出自哪个文件。如果用户原话里说不要这一列，就不要加。",
        "结果另存为一个新文件，放在第一张表旁边，文件名以「结果_合并」开头；如果原来的是 csv，也存成 xlsx。",
        "原来的文件一张都不要改、不要删、不要移动。",
      ],
      instruction,
      done: "一共读了几张表、每张各有多少行、合并后一共多少行、去掉了几条重复行、结果文件的完整位置。哪张表有问题也一并说清楚。",
    });
  },
  summaryHints: ["一共读了几张表", "合并后一共有多少行", "去掉了多少条重复行", "结果文件在哪个位置"],
};

