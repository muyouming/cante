// 把长文档总结成一页要点（#74）。
//
// 总结最容易出的问题是「看着都对，但你不知道它从哪来」。所以这条卡片的重点
// 不是写得漂亮，而是每一条要点后面都必须标出出处，让用户能翻回原文核对。
import type { TaskDef } from "./types.ts";
import { buildPrompt } from "./prompt.ts";

const DOC_TYPES = ["docx", "doc", "pdf", "txt", "md", "rtf"];

const summary: TaskDef = {
  id: "doc.summary",
  title: "把长文档总结成一页要点",
  example: "把这份年度报告总结成一页要点，每条后面标出是从哪里来的",
  group: "文书",
  needs: "files",
  accept: DOC_TYPES,
  plan: [
    "先把每份文档读一遍，记住哪里讲了什么",
    "把内容归纳成一页要点，一条说一件事",
    "每条要点后面标出它是从哪一段、哪个文件来的",
    "要点另存成一个新文件，原来的文档一份都不动",
  ],
  risks: [
    // #88 — 文书这一路的典型交法就是 WPS：她存的是 WPS 自己的格式，我们读不了。
    // 这件事要在确认页上先说清，不能等跑起来才说（选文件那一步也有同一句提示）。
    "如果交来的是 WPS 自己保存的文件（不是 Word 文件），我读不了；请你先在 WPS 里点「另存为」存成 Word 文件（.docx）再给我。",
    "文档很长、又没有小标题时，我只能把出处写到「第几段」或「第几页」，没法精确到某一句话；这种我会把段落序号写清，你翻回原文时按段找。",
    "文档里的图片和扫描页，我读不到里面的字；遇到这种地方我会说明缺了什么，不会照着旁边的文字替你补。",
    "同一件事在几处都提到时，我会合并成一条，并把几处出处都列上，请你核对有没有漏掉重要的说法。",
    "要点是我按原文归纳的，可能漏掉你觉得最重要的那一句，请你对着原文核对一遍。",
  ],
  prompt(files, instruction) {
    return buildPrompt({
      what: "把下面的一份或几份文档读一遍，总结成一页要点，每条要点都要标出来自哪里。",
      files,
      how: [
        "先逐份读一遍，用一两句话告诉我：每份文档大概讲什么、有多少页或多少段、有没有读不到的地方。",
        "把内容归纳成一页要点，一条说一件事，用大白话写，不要照抄整段。用户如果说了要重点讲哪一块，以用户原话为准。",
        "每一条要点后面都要用括号标出出处，写成「（来自：文件名，第 X 段 / 第 X 页）」这样的形式；同一件事出自几处，就把几处都列上。",
        "文档里有图片、扫描页这类读不到的内容时，单独写一条说明「这里读不到」，不要跳过，也不要编一段填进去。",
        "要点数量按内容多少来定，不要为了凑数把一句话拆成三条，也不要为了简短漏掉重要的数字和日期。",
        "结果另存为一个新文件，放在第一份文档旁边，文件名以「结果_要点」开头。原来的文档一份都不要改、不要删、不要覆盖。",
      ],
      instruction,
      done: "一共读了几份文档、总结出多少条要点、有没有读不到的地方、哪些要点请你重点核对、结果文件的完整位置。",
    });
  },
  summaryHints: ["一共读了几份文档", "总结出多少条要点", "有没有读不到的地方", "结果文件在哪个位置"],
};

export const SUMMARY_TASKS: TaskDef[] = [summary];
