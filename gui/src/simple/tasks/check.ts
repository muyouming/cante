// 「帮我检查」的两张卡片（#84 核对族）。
//
// 到目前为止，表格任务全是「帮我生成」：合并、汇总、整理、对比都产出一份新东西。
// 但对把数字交给领导的行政/财务来说，检查往往比生成更值钱——她最怕的不是算得慢，
// 而是算错了没人发现。所以这两张卡只读不写回：把该核的地方逐个核一遍，把对不上
// 的地方连同原值一起列出来，让人自己判断，绝不替她改表、也绝不下结论。
//
// 跟 excel.ts / sheet.ts 的样板一致：plan 是固定文字（确认页每次都一样），risks
// 是能对着自己文件核对的具体情况，prompt 走公共信封。
import type { TaskDef } from "./types.ts";
import { buildPrompt } from "./prompt.ts";

const SHEET_TYPES = ["xlsx", "xls", "csv"];

