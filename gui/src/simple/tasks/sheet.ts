// 表格的「行」和「列」两件常用事（#74）：
//   挑行——从一张大表里只留下符合条件的记录；
//   拆列——把挤在一列里的两样东西分成两列。
//
// 和 excel.ts 的样板一致：plan 是固定文字（确认页每次都一样），risks 是能被
// 用户对着自己文件核对的具体情况，prompt 走公共信封。
import type { TaskDef } from "./index.ts";
import { buildPrompt } from "./index.ts";

const SHEET_TYPES = ["xlsx", "xls", "csv"];

/** 从一张大表里挑出想要的行。 */
const filter: TaskDef = {
  id: "excel.filter",
  title: "从大表里挑出想要的行",
  example: "从这张表里把「华东区」三月的记录挑出来，另存一张新表",
  group: "表格",
  needs: "files",
  accept: SHEET_TYPES,
  plan: [
    "先读一遍表，找出可以用来挑行的列（客户、月份、金额这类）",
    "按你说的条件把符合条件的行挑出来，每一格内容都不改",
    "挑出来的行另存成一张新表，原来的表不动",
    "把一共看了多少行、挑出来多少行告诉你",
  ],
  risks: [
    "条件里的数字边界算不算（比如「1 万以上」含不含正好 1 万），我会按「含」来算，请你核对挑出来的第一行和最后一行。",
    "挑行那一列存的是文字还是数字，会影响结果：「2024/1/5」和「2024-01-05」可能被当成两种写法。",
    "那一列有空格或错别字时（「华东 」和「华东」），可能被当成两个值，漏掉你要的行。",
    "表里有隐藏的行、或者筛选没有清除时，我会按表面能看到的全部内容来挑，数字可能和你预想的不一样。",
  ],
  prompt(files, instruction) {
    return buildPrompt({
      what: "从下面这张大表里，按用户说出的条件挑出符合条件的行，另存成一张新表。",
      files,
      how: [
        "先读一遍表，用一两句话告诉我：每一列是什么、哪一列适合用来挑行、有没有合并单元格和公式。",
        "挑行的条件以用户原话为准。用户说的条件不够清楚时（比如「金额大的」没说多少以上），先问我一句，不要自己定一个数。",
        "只挑行，不要改内容：被挑中的行每一格都照原样保留，日期还是日期，数字还是数字，编号前面的 0 不要丢。不要替用户改错别字，也不要合并相似的值。",
        "被挑出来的行，顺序照原来的先后；原来的表头留着，不要重新起名。",
        "结果另存为一个新文件，放在原表旁边，文件名以「结果_挑出」开头；如果原来是 csv，也存成 xlsx。原来的文件一张都不要改、不要删、不要移动。",
      ],
      instruction,
      done: "一共看了多少行、按什么条件挑的、挑出来多少行、结果文件的完整位置。",
    });
  },
  summaryHints: ["一共看了多少行", "按什么条件挑的", "挑出来多少行", "结果文件在哪个位置"],
};

/** 把一列拆成两列。 */
const split: TaskDef = {
  id: "excel.split",
  title: "把一列拆成两列",
  example: "把「姓名电话」这一列拆成姓名和电话两列",
  group: "表格",
  needs: "files",
  accept: SHEET_TYPES,
  plan: [
    "先看一遍这一列，找出分隔的规律（空格、逗号、括号这类）",
    "按你说的规律把这一列拆成两列，原来的列留在原处",
    "结果另存成一张新表，原来的表不动",
    "拆不干净的行单独列出来提醒你",
  ],
  risks: [
    "同一列里写法不统一时（有的用空格、有的用逗号），我会按最常见的那种拆，其余的行原样留下并标出来。",
    "号码和日期前面的 0（比如 0755 开头、月份 03）我会按原样保留，不替你删也不替你补。",
    "括号或备注（比如「张三（销售部）」）会整体算进第二列，可能和你想分的不一样。",
    "拆出来有一列是空的时候，我会留空，并在最后告诉你有多少行是这种情况。",
  ],
  prompt(files, instruction) {
    return buildPrompt({
      what: "把下面这张表里的一列，按用户说的规律拆成两列。",
      files,
      how: [
        "先看一遍用户指定的那一列，告诉我这一列大概长什么样、能看出哪几种写法、你打算按什么规律拆。",
        "拆分的列和规律以用户原话为准。用户没说清楚用哪个分隔符时，先问我一句。",
        "拆分只增加内容，不改内容：原来的那一列留在原处不要动，拆出来的两列放在它旁边。每一格照原样搬过去，编号和日期前面的 0 不要丢。",
        "同一列里写法不统一时，按最常见的那种拆；拆不出来的行整格原样保留，不要硬拆成一半，并在最后告诉我有多少行。",
        "结果另存为一个新文件，放在原表旁边，文件名以「结果_拆列」开头。原来的文件不要改、不要删、不要移动。",
      ],
      instruction,
      done: "按什么规律拆的、拆成了哪两列、一共拆了多少行、有多少行没拆干净，以及结果文件的完整位置。",
    });
  },
  summaryHints: ["按什么规律拆的", "拆成了哪两列", "有多少行没拆干净", "结果文件在哪个位置"],
};

export const SHEET_TASKS: TaskDef[] = [filter, split];
