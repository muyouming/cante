// 「关于」这一页的文字（#151）。
//
// 她不会去网页或安装目录里找许可说明，所以许可说明得跟软件一起送到她手上。
// 这一页要做的事只有一件：把「这个软件用了别人的东西、它们的许可是什么」讲清楚，
// 同时不让她觉得这是需要她读懂的东西。
//
// 这里的每一句都是人写的文案，所以按产品律：全中文、零术语、不卖萌。条目本身
// （名字 / 版本 / 许可 / 原文）是数据，不在这里，也不进内联文案预算 —— 那份预算
// 只管人写的句子。

import { COMMON } from "./copy.ts";

export const ABOUT = {
  /** 首页右上角那个安静的入口（就放在 COMMON 里，别的入口也在那儿）。 */
  entry: COMMON.about,
  /** 这一页的第一句：先说清这是别人的东西。 */
  title: "这个软件用到了很多别人免费公开的代码。",
  /** 第二句：说清她不用读，但她有权知道。 */
  lead: "这里是它们的许可说明。你不用看，但你有权知道。",
  /** 列表的表头。 */
  listTitle: "用到的清单",
  /** 一条里每一列的意思。 */
  nameColumn: "名称",
  versionColumn: "版本",
  licenseColumn: "许可",
  /** 展开许可原文那一行的动作。 */
  showText: "查看许可原文",
  /** 确实没附带原文时照实说，不替它补。 */
  missingText: "这份没有附带原文",
  /**
   * 把数字摆出来：一共多少份、多少份不同的说明、多少份没附带原文。
   * 数字来自生成物，不是这里写死的。
   */
  summary: (packages: number, uniqueTexts: number) => `一共 ${packages} 份，其中 ${uniqueTexts} 份不同的许可说明。`,
  missingNote: (missing: number) => `有 ${missing} 份没有附带原文，这里照实标出来，不替它们补。`,
  /** 万一生成空清单，也不能是一片空白。 */
  empty: "清单是空的，这不对，请找懂电脑的同事看看。",
} as const;
