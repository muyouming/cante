// 「结果在哪、怎么打印」的面向用户中文。
//
// 她做完一件事之后，下一步通常是两件事：把结果**打印**出来给领导签字，或者
// **发到微信**给同事。发微信那条路在 copy-share.ts（只复制、绝不替她发送）；
// 这里补的是打印：我们不替她按打印（会浪费纸），只告诉她文件在哪、怎么打开、
// 按哪个键。
//
// 硬约束和别的 copy 模块一样：全中文、零术语。特别是不印机器路径（「路径」是
// 黑名单词），要说「文件就在桌面上」这种她能直接对上号的话。位置的判断在
// location.ts，这里只放话。

import type { PlaceKind } from "./location.ts";

/** 每个位置一句，必须是完整的、她看得懂的话。other 给出路（点按钮去找）。 */
export const LOCATION: Readonly<Record<PlaceKind, string>> = {
  desktop: "文件就在桌面上。",
  downloads: "文件就在「下载」文件夹里。",
  documents: "文件就在「文档」文件夹里。",
  pictures: "文件就在「图片」文件夹里。",
  wechat: "文件就在微信收文件的文件夹里。",
  other: "文件就在原来那个文件夹里，可以点「打开所在文件夹」找到它。",
};

export const PRINT = {
  /**
   * 一句话说清打印怎么做：先打开，再按 Ctrl+P。产品以 Windows 为先，所以按
   * Windows 的键说；打开用的是系统默认程序（表格就是 Excel / WPS），因此不写死
   * 某个程序的名字。
   */
  hint: "想打印出来：先点「打开文件」把它打开，再按 Ctrl+P 就能打印。",
} as const;
