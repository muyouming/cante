// 她**正在做**的时候点右上角关掉，屏幕上必须先说的那一句。
//
// 关掉应用这件事本身她有权做（我们不拦她，也不记她"强行关了"）。但手里那件活还没
// 做完时，关掉就意味着它**停下来**了——所以这句话要把两件事说清：
//
//   1. 还有一件事没做完；
//   2. 关掉它，这件事就会停下来。
//
// 然后给她两个选择，而且默认的答案是「继续做」（安全答案就在焦点上，见
// CloseGuard 的 initialFocus）。不提文件会不会丢：原来的文件本来就没被改动，说了
// 反而吓她。
//
// 硬约束同别的 copy 模块：全中文、零术语，不出现路径 / 进程 / 会话这类词
// （copy-guard.test.ts 会扫）。
export const CLOSE = {
  /** 浮层标题：她一眼看到的是「没做完」这件事本身。 */
  title: "现在还有一件事没做完",
  /** 标题下面那一句：关掉会发生什么。 */
  body: "关掉就会停下来，这件事就不会再往下做了。",
  /** 默认焦点在这颗按钮上（安全答案是已经在焦点上的那个）。 */
  keep: "继续做",
  /** 她确认要关：放行，不再问第二遍。 */
  leave: "关掉",
} as const;
