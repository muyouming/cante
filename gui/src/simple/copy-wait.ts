// 「还要多久」那一句的文案。
//
// 她慢的时候不知道还要等多久（实测最慢 846 秒，典型 30–60 秒）。但产品**不能**
// 承诺一个猜出来的时间：说「还有 2 分钟」而实际再等 10 分钟，比不说更伤信任
// （Wharton 那份实证：空口保证会掉信任）。
//
// 所以这里说的话只有两种，都**基于观察**，都不打包票：
//
//   1. 还在做、时间还正常：报一个**从真机样本里量出来的常见范围**；
//   2. 超过那个范围的九成位之后：改口说「比一般情况久」——不编一个新的倒计时。
//
// 两个数字来自 `wait.ts` 的 `WAIT_SAMPLES`（普查报告与 Windows 验收里记下的真实耗时），
// `wait.ts` 负责算和判断，这里只放说给她听的话。文案里**不许**出现「保证 / 一定 /
// 马上 / 立刻」这类打包票的词，也不做倒计时动画（落空会更明显）。
//
// 为什么单独一个 copy 模块：copy-guard / tone / readability 三道闸门都会扫
// `copy*.ts` 的字符串，集中在这里才有人能一眼校对。
export const WAIT = {
  /**
   * 常见时长。`lo`/`hi` 是过去几次真机做下来观察到的范围，不是我们对这一次的承诺。
   * 措辞用「一般要」而不是「最多」——后者就是一句会被落空保证。
   */
  usual: (lo: string, hi: string) => `这类事一般要 ${lo} 到 ${hi}。`,
  /**
   * 说清上面那句的出处：它是看过来的，不是替这一次打的包票。
   * 用「只是 … 看到的」而不是「不是保证」——后者反而把「保证」两个字塞进她眼里。
   */
  observed: "这只是以前几次实际做下来看到的，每次快慢可能不一样。",
  /**
   * 超过九成位之后改口：承认它比一般情况久，同时说清还在做、她没有被困住。
   * 这里**不**给新数字（那又会变成一次承诺），也**不**说「连不上」——遇到真的断线，
   * 停滞那一屏会整屏替掉这里，两句话不重叠。
   */
  longer: "这次比一般情况久。还在做，你也可以先停下来。",
} as const;
