// 确认页上「去掉一个文件」的面向用户中文（本轮 P0）。
//
// 王姐会选错文件（桌面上「副本-副本.xlsx」）。确认页原来只给她看文件名，选错了
// 只能返回重来、或者硬着头皮往下走，结果落在她不想要的文件旁边。这里的话只说
// 三件事：怎么去掉这一份、去掉之后还剩什么、去掉之后怎么反悔或者重新选。
//
// 两条说得清清楚楚：
//   * 「不用这个」只是不再拿它当输入，**不是删除**——她的文件还在原来的地方；
//   * 去掉最后一个之后，这件事没有输入就跑不了，所以要给她一句为什么 + 一条出路。
//
// 全程零术语：说「文件」和「原处」，不说「路径」。
/**
 * 微信族的组名（`TaskGroup` 的一个值）。**不是给用户看的句子**，是一个稳定标识：
 * 那一族的文件是**加法不是门槛**——内容可以整段贴在话里（微信那一屏的粘贴入口），
 * 所以她在确认页把选的文件都去掉之后，那一件仍然做得成，不该被「没有文件」拦住。
 */
export const PASTES_CONTENT_GROUP = "微信";

export const CONFIRM_FILES = {
  /** 文件名后面那半句：它在哪个文件夹里（文件名单独显示，方便她认是哪一份）。 */
  fileInFolder: (folder: string): string => `在 ${folder}`,
  /** 每个文件旁边那个按钮：不再拿这一份当输入。 */
  removeOne: "不用这个",
  /** 屏幕阅读器念这个按钮时用的全名（要说清是哪一份）。 */
  removeLabel: (name: string): string => `不用这个：${name}`,
  /** 反悔按钮：把刚去掉的那一份加回来。 */
  undoRemove: "加回来",
  /** 「加回来」按钮的全名，同样带上文件名。 */
  undoLabel: (name: string): string => `加回来：${name}`,
  /** 去掉几份之后她还能反悔：这一条只在真去掉过东西时出现。 */
  removedHeading: "已经去掉的（你的文件还在原处）",
  /** 一份文件都不剩时的出路：重新打开选文件的窗口。 */
  pickAgain: "再选一个",
  /** 一份都不剩时那个方框的标题。 */
  emptyHeading: "现在一份文件都没有了",
  /** 为什么现在做不了：这件事需要她选的文件。 */
  emptyBody: "这件事要用到你选的文件。一份都没有，开始也做不成。",
  /** 出路：重新选一份就行。 */
  emptyPickHint: "想继续的话，再选一个文件就行。",
  /** 开始按钮旁边那句「为什么现在别开始」。 */
  cannotStart: "现在没有文件，开始也做不成。先选一个再开始。",
} as const;
