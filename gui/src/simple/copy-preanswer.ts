// 「动手前她就能答的问题」的文案与选项。
//
// 为什么要有这个文件：真机普查的结论是——26 次运行里 6 次助手**停下来问用户**，
// 问的都是同一类判断（普查报告 gui/scripts/sweep/report.md 的「一句话」一节）：
// 两张表的列名对不上按哪张算（excel.merge）、PDF 加了密码（pdf.merge）、扫描件要不要
// 逐字识别（pdf.toword）、文书缺关键信息（doc.notice / doc.leave / doc.report）。
// 同一类判断在别的卡上也写着「先问我一句」「必须先问我确认」（check.ts / invoice.ts /
// admin.ts）——这不是意外，是常见情况；而它们她其实在动手前就能答：她想让哪张表说了
// 算、她要的是明细还是含合计。跑到一半才问，对她就是「等了一会儿才发现要我决定」。
//
// 所以把这些问题挪到确认页上，每个问题给两条能选的、各带一行「选它会怎样」的小字，
// 默认值就是**卡片现在本来会做**的那一种：她可以一个字都不改，直接点开始。
//
// 她选了什么，由 tasks/prompt.ts 写进指令信封的【她事先说过】一节；有测试盯着这条线
// （src/simple/preanswer.test.ts）——只显示在界面上、没进指令，等于又白等一次。
//
// 本轮接线的是 excel 那四张卡（合并 / 对比 / 整理 / 汇总）；report.md 里另外三次
// 「停下问」在 pdf 和文书族，那几张卡的文件不在本轮的改动范围内，所以还没接线。
//
// 约定（有测试挡着）：
//   * 每条选项的第一个标着 isDefault，它是默认值，也是「最安全/最常见」的那一种；
//   * 每条选项都有 note，解释选它会怎样——只给结论不给解释，她没法判断；
//   * envelope 是真正发给助手的那一句，里面必须写明「不要再为这件事停下来问她」；
//   * 没有对应判断的卡片在这里没有条目，确认页上也不会有这一节。

/** 一个可选项：她看到的两行字 + 真正发出去的那一句。 */
export interface PreAnswerOption {
  /** 选项本身，短一点，她一眼能读完。 */
  readonly label: string;
  /** 选它会怎样——一行小字，写清结果里会发生什么。 */
  readonly note: string;
  /** 拼进指令的那一句（发给助手的说法）。 */
  readonly envelope: string;
  /** 默认值：卡片现在本来就会这么做的那一种。每条选项里只有一个标它。 */
  readonly isDefault?: boolean;
}

/** 一个「她动手前就能答」的问题。 */
export interface PreAnswerDecision {
  /**
   * 稳定的短编号（界面和测试都用它），全局不许重样（有测试）。
   */
  readonly id: string;
  /** 确认页上的问题，一句平实中文。 */
  readonly question: string;
  /** 可选项，默认那一条排在最前面。 */
  readonly options: readonly PreAnswerOption[];
}

