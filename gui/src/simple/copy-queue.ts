// r13 队列（一次说好几件事）的界面文案。
//
// 王姐经常一次要办好几件（合表、查重、整理文件夹）。这一块界面只干三件事：
// 让她看见"排了什么、还剩几件、下一件是什么"，让她随时能**停掉剩下的**，
// 并且在每一件动手之前照样停下来问她。
//
// 有一句话必须一直在场：排队不等于自动做完——每一件都还要她点头。这也是
// 为什么这里没有"全部自动做完"这种按钮：那和产品律（动手前先问人）直接冲突。
//
// 按项目惯例，组件里不留裸中文，全部集中在这里校对；用词不许出现模型、
// token、prompt、会话、上下文、权限模式、工具调用、diff、worktree、路径等术语。
// 跟着数据变的那几句（几件、哪一件）在 `queue.ts` 里生成。

export const QUEUE = {
  // ---- 首页那一块 ---------------------------------------------------------
  /** 小标题：说的是"排好等着做的事"，不是"任务列表"这种系统说法。 */
  homeTitle: "排队等着做的事",
  /** 一句话讲清规矩，跟定时任务用的是同一条规矩。 */
  homeConfirmNote: "每一件动手前都会先停下来问你一句，你点头它才开始。",
  /** 去确认排在最前面的那件（或者已经停在确认页的那件）。 */
  homeOpen: "去做这一件",
  /** 停掉还没轮到的那些。 */
  homeStop: "停掉剩下的",
  /** 停掉之后说清楚：正在做的那件不会因此被打断。 */
  homeStopNote: "停掉的只是还没轮到的那些；正在做的这件不会被打断。",

  // ---- 「说需求」这一步：先把这件记下来 -----------------------------------
  /** 她一次要说好几件事时，先记下来，回去挑下一件。 */
  keepForLater: "先记下来，等会儿一起做",
  /** 记下来之后照样要她点头，先把这句说在动手之前。 */
  keepHint: "记下来以后，每一件动手前都还会先问你一次。",

  // ---- 确认页上那一条 -----------------------------------------------------
  /** 确认页上那一条的小标题。 */
  stripTitle: "排队等着做的事",
  /** 手里这件就在队列里：说清它排第几、还剩几件。 */
  stripHere: (position: number, remaining: number) => `你排了 ${remaining} 件，这件排在第 ${position} 件。`,
  /** 手里这件不在队列里（她是从卡片直接进来的）：不替她做主，给她一个选择。 */
  stripInsert: (remaining: number) => `你排了 ${remaining} 件，这件还没排进去；想先做这件也可以。`,
  /** 先做手里这件。 */
  doThisOne: "先做这件",
  /** 跳过手里这件，去做排好的下一件。 */
  skipThisOne: "跳过，做下一件",

  // ---- 结果页：下一件已经在等她确认了 -------------------------------------
  /** 队列把下一件摆到确认页时，先把这次的结果留给她看完。 */
  resultNext: (remaining: number) => `看下一件（还排着 ${remaining} 件）`,
  /** 说明下一件只是摆好了，没有自己动手。 */
  resultNote: "下一件已经在等你确认了，它不会自己动手。",
} as const;
