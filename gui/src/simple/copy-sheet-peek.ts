// 「表里是什么样」的面向用户中文——她自己能核对的那几个数。
//
// 结果核对原本只回答「文件在不在、能不能打开」（copy-verify.ts）。她真正会问的是
// 另一个问题：这就是我要的那份内容吗。我们不替她下结论（那是自证），而是把三个她
// 能自己对着看的东西照抄出来：第一行下面的行数、第一行的列名、最前面几行的内容。
//
// 数字由 sheet-peek.ts 从产出文件里真读出来后传进来；这里只有字，没有判断。
// 和别的 copy 模块一样：全中文、零术语，句子短、一句只说一件事。

export const SHEET_PEEK = {
  /** 核对区的小标题。 */
  title: "表里是什么样",
  /** 行数：第一行是列名，所以说的是它下面的行数——她自己数的时候对得上。 */
  rows: (count: number): string => `第一行是列名，下面有 ${count} 行。`,
  /** 列名小标题；列太多时明说只列了前面几个、一共几个。 */
  columnsLabel: (shown: number, total: number): string =>
    total > shown ? `列名是（前 ${shown} 个，一共 ${total} 列）：` : "列名是：",
  /** 数据行不超过首屏时，说「都在这儿」，不谎称还有更多。 */
  headAll: "表里的内容都在下面，每行从左到右：",
  /** 数据行比首屏多时，明说只照抄了最前面几行。 */
  headMore: (shown: number): string => `最前面 ${shown} 行，每行从左到右：`,
  /** 表比照抄的列宽时，说清每行只列了前面几格。 */
  narrowed: (shown: number): string => `这张表比较宽，每行只列了前 ${shown} 列。`,
  /** 只有列名、一行数据都没有。 */
  onlyColumns: "这个表只有列名，还没有内容。",
  /** 表是空的。 */
  empty: "这个表里没有内容。",
  /** 读不出来（文件坏了、被占用、工具报错）。不假装读过。 */
  unknown: "这张表里的内容我这次没能读到，你可以自己打开看一眼。",
  /** 这台电脑没有读表格的工具。 */
  noTool: "这台电脑还读不出表格里的内容，你可以自己打开看一眼。",
} as const;
