// 「她点了停下来」之后，屏幕上必须说完整的那几句。
//
// 她点完「停下来」，最想知道三件事（产品律 2「别弄坏我的东西」+ 律 3「出错能看懂」）：
//   1. 做到一半的东西还在不在、在哪儿；
//   2. 她原来的文件动了没有；
//   3. 接下来还能做什么。
//
// 这里只放话。结论由 stop.ts 从**已有的事实**算出来：原来的文件动没动、新做出了
// 几个文件，都看 run.impact（运行前后各一次快照、diff 出来的），不新造任何状态。
//
// 为什么第三步不说「接着做」：产品现在**不支持**从停下的地方接着跑——「停下来」会把
// 这一轮结束掉，桥不会把做到一半的那一步续上（见 CONTRACT.md 对「重做一遍」的说明）。
// 摆一个点了没用的按钮比不摆更坏，所以这里只给「再跑一次（从头做一遍）」这条真能走
// 的路。
//
// 硬约束同别的 copy 模块：全中文、零术语，不说「中止 / 取消 / 进程 / 会话」，就说
// 「停下」。
export const STOPPED = {
  /** 1/3：做到一半的产出。`count` 是这次真的新做出来的文件个数。 */
  partial: (count: number): string =>
    count > 0
      ? `你点下「停下来」的时候，已经做出了 ${count} 个新文件，列在下面。`
      : "你点下「停下来」的时候，还没有做出新文件。",
  /** 2/3：原来的文件。产品对文件的承诺原话（产品律 2）。 */
  originalsSafe: "原来的文件没有被改动，都还在。",
  /** 2/3 的另一种：她这次勾过「直接改原来的文件」，而且真改动了。 */
  originalsTouched: (count: number): string =>
    `这次改动过原来的文件（${count} 个），可以用下面的「一键撤销」还回去。`,
  /** 3/3：下一步。说清是**从头重做**，不假装能接着跑。 */
  nextStep: "想再来一次，就点下面的「再跑一次」，它会把这件事从头做一遍。",
} as const;
