// 「把结果复制成微信能贴的文字」的面向用户中文。
//
// 单独一个文件，是为了不去动别的 workstream 正在改的 copy.ts。这里只讲两件事：
// 点一下会发生什么（只是复制，不替你发送），以及读不出来时她自己能怎么办。
// 措辞零术语、全中文，和别的 copy 模块保持同一语气。

export const SHARE = {
  /** 文件列表里给表格结果的按钮。 */
  copyButton: "复制成微信能贴的文字",
  /** 按钮旁边一直挂着的一句提醒：复制不等于发送。 */
  hint: "只是复制成文字，你自己到微信里粘贴，Cante 不会替你发送。",
  /** 复制成功。 */
  copied: "已经复制好了。打开微信，在要发的地方按 Ctrl+V 粘贴就行——发不发还是你自己决定。",
  /** 复制本身没成功（例如系统不让写剪贴板）。 */
  copyFailed: "没能复制上。你可以先用 Excel 打开这个文件，选中要发的内容再复制。",
  /** 这台电脑根本没有读表格的工具。 */
  toolUnavailable:
    "这台电脑还读不出表格里的内容，所以没法帮你复制。你可以先用 Excel 打开它，选中要发的部分自己复制。",
  /** 表是空的。 */
  empty: "这个表里没有能复制的内容。",
  /** 工具在，但表读不出来（坏了、加密了、被占用了……）。 */
  readFailed:
    "这个表暂时读不出来。你可以先用 Excel 打开它，选中要发的部分自己复制，或者过一会儿再试。",
} as const;

/**
 * 读表失败时的一句可操作说明；把工具自己说的原因附在后面，方便她核对。
 *
 * 原因可能已经是中文（cante-sheets 的错误都是中文），也可能是别的东西，所以
 * 只做兜底拼接，不假设它的语言。
 */
export function shareReadFailed(reason: string): string {
  const trimmed = (reason ?? "").trim();
  if (trimmed === "") return SHARE.readFailed;
  return `${SHARE.readFailed}（${trimmed}）`;
}
