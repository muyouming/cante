//
// 她的处境常常是反过来的：不是"想做什么、去找哪张卡"，而是**手里刚拿到一个
// 文件**（微信发来的报名表、同事给的账单），不知道该选哪张卡。所以这里把
// 「按文件类型最可能要做的那几件事」写成一句句人话，她点一句就等于选了那张卡。
//
// 文案的规矩和别处一样：全中文、零术语、不卖萌、不承诺耗时。每一条都必须是
// **一句话人话**（不是卡名）——卡名她读起来还是在做选择题，而"把这几张表合成
// 一张"是她自己会说的话。
